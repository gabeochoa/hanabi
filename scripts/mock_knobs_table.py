#!/usr/bin/env python3
"""Print docs/mock-knobs.md: every HANABI_* environment variable the mock
backend reads, where it is read, and how many UI fixtures set it."""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ["src/api/mock_client.h", "src/api/mock_faults.h", "src/api/mock_journal.h", "src/api/mock_scale.h"]
NAMED = {
    "HANABI_MOCK_JOURNAL": ("src/api/mock_journal.h", "path of a JSONL file; every send the mock accepts appends one line {session_id, kind, text, attachments, at_unix_ms, local_id?}; the e2e verb clear_mock_journal truncates it"),
    "HANABI_MOCK_PAGE_DELAY_MS": ("src/api/mock_faults.h", "sleep this long before answering a windowed or resumed transcript read, so a load-earlier state can be photographed"),
    "HANABI_MOCK_SCALE": ("src/api/mock_scale.h", "<n> (1..1000, default 1): every seeded session gains n-1 clones (<id>x<copy>), each carrying the base transcript n times over with numeric seq ids 1..N, last_seq=N, stepped timestamps; sessions, messages per thread, tool rows and attachments all scale by n, deterministically; the base rows are untouched, so every fixture that names them still holds"),
    "HANABI_MOCK_OPEN_FAIL_ONCE": ("src/api/mock_faults.h", "<session id>[:<reason>]: the first open of that session fails (a transport failure, not a refusal) with the reason; the next open succeeds"),
}
GROUPS = [
    ("Fixtures and seeds", re.compile(r"^HANABI_(?!MOCK_)")),
    ("Failure and refusal injection", re.compile(r"_(FAIL|REFUSE|DROP|CLOSE|DENY|GONE)")),
    ("Holds, delays and clocks", re.compile(r"_(HOLD|DELAY|NOW|CLOCKS|LIVE)")),
    ("Capability toggles", re.compile(r"_NO_")),
    ("Other mock state", re.compile(r".")),
]


def first_line(path, name):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            if f'"{name}"' in line:
                return n
    return 0


def main():
    knobs = {}
    for src in SOURCES:
        text = open(os.path.join(ROOT, src), encoding="utf-8").read()
        for name in re.findall(r'getenv\("(HANABI_[A-Z0-9_]+)"\)', text):
            knobs.setdefault(name, src)
    for name, (src, _) in NAMED.items():
        knobs.setdefault(name, src)
    fixtures = {}
    for f in glob.glob(os.path.join(ROOT, "tests/ui/*.e2e")):
        head = open(f, encoding="utf-8", errors="replace").read(4000)
        for name in knobs:
            if name in head:
                fixtures[name] = fixtures.get(name, 0) + 1
    out = ["# Mock backend knobs", "",
           "Generated by `scripts/mock_knobs_table.py` from the mock's own `getenv` calls;",
           "re-run it after adding a knob. The mock is in-process (`api::MockClient`,",
           "selected when `HANABI_BACKEND` is unset or `mock`); a fixture sets these on",
           "its `# env:` line, and the app honours them when launched by hand too.", ""]
    placed = set()
    for title, rx in GROUPS:
        rows = sorted(k for k in knobs if k not in placed and rx.search(k))
        if not rows:
            continue
        out += [f"## {title}", "", "| Variable | Read at | Fixtures | Meaning |", "|---|---|---|---|"]
        for k in rows:
            placed.add(k)
            src = knobs[k]
            line = first_line(src, k)
            meaning = NAMED.get(k, (None, ""))[1]
            out.append(f"| `{k}` | `{src}:{line}` | {fixtures.get(k, 0)} | {meaning} |")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
